import mongoose from "mongoose";

const helpRequestSchema = new mongoose.Schema(
  {
    name: {
      type: String,
      required: true,
    },

    phone: {
      type: String,
      required: true,
    },

    message: {
      type: String,
      required: true,
    },

    status: {
      type: String,
      enum: ["Pending", "Resolved"],
      default: "Pending",
    },
  },
  {
    timestamps: true,
  }
);

const HelpRequest = mongoose.model(
  "HelpRequest",
  helpRequestSchema
);

export default HelpRequest;